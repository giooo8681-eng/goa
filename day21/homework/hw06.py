# 6)შექმენით ფუნქცია Even ფუნქცია სადაც გადაცემთ სიას,ამ სიაში უნდა იყოს კენტების და ლუწებიც.თქვენი დავალება არის რომ ამ რიცხვებიდან დააბრუნოთ მხოლოდ ლუწებიი
def even(lst):
    name=[]
    for i in lst:
        if i%2==0:
            name.append(i)
    return name
print(even([3,4,6,7,8]))
        
        



